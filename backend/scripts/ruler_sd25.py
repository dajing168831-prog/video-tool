def t3_edit_verb(p, ctx):
    """`sd25-pe:561`「编辑@视频1，只把<原对象或区域>修改为<目标内容>」。

    🩸 动词接受「修改为/替换为/改为/改成」：模板写 `修改为`，但**官方填写示例**
    `sd25-pe:584` 用的是「只把经过长椅前方的红色自行车和骑行者**替换为**@图片1中…」。
    只认 `修改为` 会把官方自己的示例判红。
    """
    sec = _sec(p, "【编辑目标】")
    # 🩸 2026-10-26（穷举 E2）：这条只管**有改动宾语**的编辑句。
    #   ① 只写补充说明（「编辑视频：@视频1，在背景里加一只橘猫」）没有"把…改成"，
    #      那是 API 触发词兜底形态（`edit_spec` `:1546-1549`），不该按模板句判；
    #   ② 官方 `:561` 的限定词是**作用在每个宾语上的「只」**。
    # 🩸 2026-10-28（2.5 轮，当前产出实测）：这一行以前是**早退**——
    # 【编辑目标】里一个官方动词都没有时直接返回空，等于放行。
    # 真实产出「只把X的服装**换成**@图片1中的服装」就是这么漏过去的
    # （「换成」不在 `sd25-guide:88` 的触发关键词里，也不在模板 `:561` 里）。
    # 现在：有「只把」却没有官方动词 → 判红；连「只把」都没有（只写补充说明
    # 的 API 兜底形态）→ 仍放行，由别的规则管。
    # 🩸 2026-10-29（变异测试）：**逐句**判，不再整段判。
    #   原来在整段上找一个官方动词就够，于是「只把产品替换为…」这句好的会
    #   把前一句「把人物**换成**…」的毛病一起掩盖掉（变异测试就是这么漏的）。
    #   判据按 `:561`/`:584` 的**句**形态：含「把」的编辑句必须
    #   ① 用官方动词（`sd25-guide:88`：修改/替换/改成）② 带「只」限定。
    #   不含「把」的补充说明句（`sd25-guide:88` 示例「@video1 中加一些小动物」）跳过。
    # 🩸 2026-10-29（穷举 E13 产品-多行）：宾语边界以前写的是 `[^，,。]`，
    #   等于**顺手禁止了宾语里出现逗号**。那不是判据 —— 官方 `:561` 模板
    #   `只把<原对象或区域>修改为<目标内容>` 和 `:584` 示例
    #   `只把…红色自行车和骑行者替换为@图片1中的…` 都只给句式，
    #   **没有一句说宾语不许带逗号**；拿"样例恰好没逗号"反推成禁令，
    #   正是 `official-silence-is-not-a-criterion` 那个坑。
    #   同层另一家 `ruler_sd20.py:1252/:1272` 用的是 `将其中的(.{1,40}?)替换为`
    #   —— `.` 本来就允许逗号。同一件事两家判据打架，说明错的是这条边界。
    #   真实可达：`product_target` 取自盘点 chip 的 `desc_zh`，本机 8 条真实
    #   盘点里就有 1 条带逗号（「橙色连帽拉链外套，左胸带有白色品牌标识」）。
    #   ⇒ 边界放宽到 `[^。]`：逗号允许，句号仍挡着（不跨句误配）。
    #   `；` 和换行在上面 `re.split` 时已经切成句了，不用在这里防。
    bad = []
    for sent in re.split(r"[；;\n]", sec):
        if "把" not in sent:
            continue
        if not re.search(r"(修改为|替换为|改为|改成)", sent):
            # 编辑句形态 = 「把 + 宾语 + 动词」；纯补充说明没有这个结构。
            if re.search(r"把[^。]{1,60}?(换成|变作|变成|调成|调为|转为)", sent):
                bad.append("编辑句用了官方词表外的动词"
                           "（`sd25-guide:88` 只收「修改/替换/改成」）")
            continue
        if not re.search(r"只把[^。]{1,80}?(修改为|替换为|改为|改成)", sent):
            bad.append("编辑句缺「只把…修改为/替换为」")
    return bad


