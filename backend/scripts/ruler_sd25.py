def c3_identify(p, ctx):
    """指南 `:193` 编辑类要能指出改的是**哪一位**（官方示例用方位）。

    🩸 2.5 **不用** `<主体N>`（那是 2.0 的机制，`seedance-25-guide:435` 走的是
    「按首次出场顺序上传 + 编号对应」）。所以这里只查"宾语有没有指认"：
    多人画面里宾语是裸「人物」或撞车方位 → 红。
    """
    people = [x for x in (ctx.get("people") or []) if x]
    if len(people) < 2:
        return []
    cnt: dict[str, int] = {}
    for x in people:
        k = POS_ZH.get(str(x.get("position") or ""), "")
        if k:
            cnt[k] = cnt.get(k, 0) + 1
    bad = []
    for m in re.finditer(r"只把(.{1,60}?)(?:替换为|修改为|改为|改成)", p):
        obj = m.group(1).strip()
        if obj in ("人物", "角色", "其中的人物"):
            bad.append(f"宾语「{obj}」在 {len(people)} 人画面里没有指认")
        for k, n in cnt.items():
            if obj == f"{k}的人物" and n > 1:
                bad.append(f"宾语「{obj}」撞车（{k} 上有 {n} 个人）")
    return bad


_BG_VERB = re.compile(
    r"替换为|替换成|改成|改为|换成|换为|修改|重绘|重画|更换"
    # 🩸 2026-10-29（变异测试）：裸「只改背景」不含上面任何一个词 →
    #   `_bg_armed` 哑火，换背景没写「主体轮廓之外」整条放行。
    #   排除「改成/改坏/改善/改天」这类词内部的「改」，只认独立动词。
    r"|(?<![修改更])改(?![成动善造变天])")
_BG_NEG = ("不修改", "不改变", "不改动", "不改", "不变", "不替换", "不参与",
           "保持原样", "除以上明确", "不采用", "不涉及", "不需要")


#: 🩸 2026-10-28（E12 用户补充说明矩阵）：「背景音乐」里的"背景"不是画面背景。
#: 官方 `:867` 的符号表把**音乐**单列一类（`()`），`sd25-guide:231` 也把
#: 「音效、背景音乐（bgm）、对白」和画面分开管 ⇒ 声音侧的「背景X」不算换背景。
#: 实测 `背景音乐换成钢琴曲` 被判「换背景没写主体轮廓之外」= 假红。
_BG_AUDIO = ("背景音乐", "背景配乐", "背景音效", "背景噪声", "背景噪音",
             "背景音", "背景声", "背景bgm", "背景BGM")


def _bg_armed(p: str) -> bool:
    """这份提示词有没有在「改背景」。

    🩸 只认 `背景替换为` 一种写法 = **哑火**：编译器自己的正确写法是
    「只修改@视频1中主体轮廓之外的背景」「背景只修改主体轮廓之外的部分」，
    两种都不匹配 → 规则对自家输出永远沉默，正反样本也一起假绿。
    现在按**分句**判：句里提到背景、有改动动词、又不是否定/兜底句，就算改背景。
    """
    for clause in re.split(r"[。；，\n]", p):
        for _a in _BG_AUDIO:          # 先摘掉声音侧的「背景X」再判
            clause = clause.replace(_a, "音乐")
        if "背景" not in clause:
            continue
        if any(n in clause for n in _BG_NEG):
            continue
        if _BG_VERB.search(clause):
            return True
    return False


