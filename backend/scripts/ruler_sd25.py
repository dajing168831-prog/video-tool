def _case(name: str, *, n=2, picks=(0,), pos="clash",
          product=False, scene=False, cuts=None, audio="", lines=None,
          drop_zh=False, wardrobe=False, wardrobe_all=False, style_ref=False,
          style_video=False, style="", extra="", keep_off=False,
          product_target="", auto_main=False,
          wardrobe_no_ids=False, wardrobe_desc="",
          scene_desc="", desc="", zh=None):
    from app.services import edit_spec

    frame = _frame(n, pos)
    if zh:
        # D72（2026-10-29）：按用例指定**每个人**的盘点描述（默认走 `_frame`）
        frame = [dict(p, desc_zh=(zh[i] if i < len(zh) else ""))
                 for i, p in enumerate(frame)]
    if desc:
        # 盘点人物描述（多人时它就是【编辑目标】里的称谓）—— 第三个自由文本源
        frame[0]["desc_zh"] = desc
    if drop_zh:
        frame = [dict(p, desc_zh="") for p in frame]
    picked = [dict(frame[i]) for i in picks]
    slots: list[str] = []
    for k in range(len(picks)):
        slot = "person" if k == 0 else f"person{k + 1}"
        # 一个人只占一个槽位（2026-10-26，台账 D48）—— `body` 那一维已删。
        slots.append(slot)
    chg: dict = {"person": bool(picks), "person_ids": [frame[i]["id"] for i in picks]}
    if auto_main:
        # 只勾「换人物」不选人（老语义：自动取主角）——`person_ids` 空，
        # 但 `source_people` 里仍有盘点自动挑的那个人。
        chg["person_ids"] = []
    if product:
        chg["product"] = True
        slots.append("product")
        if product_target:
            chg["product_target"] = product_target
    if scene:
        chg["scene"] = True
        if scene_desc:
            chg["scene_desc"] = scene_desc
        slots.append("scene")
    if wardrobe or wardrobe_all:
        chg["wardrobe"] = True
        # 🩸 2026-10-28：只有「换装」开关、没勾人时，以前 `wid` 是空的 ⇒
        # 没有 wardrobe 槽位 ⇒ 整段一字不发。E7 因此报「开关没有落点」、
        # E2 去重从 300+ 掉到 240 —— 两次都是**量具自己没给素材**，
        # 不是产品没落点（只换装不换人是正式支持的勾法）。
        if wardrobe_no_ids:
            # 🩸🩸 2026-10-28：**有图但不点名**是 `_clauses` 里唯一走
            #   「服装换成@图片N」那条硬编码分支的形状（`wrote == 0`）。
            #   正常夹具总会自动填 `wardrobe_ids`，所以那条分支从来没被走到，
            #   它硬编码的「换成」也就一直没被 T3 抓到。老客户端 / id 不在盘点
            #   里时生产会走到这里。
            slots.append("wardrobe")
        else:
            _src = picks if wardrobe_all else picks[:1]
            if not _src:
                _src = (0,)                   # 只换装不换人：取盘点里第一个人
            wid = [frame[i]["id"] for i in _src]
            chg["wardrobe_ids"] = wid
            for k in range(len(wid)):
                slots.append("wardrobe" if k == 0 else f"wardrobe{k + 1}")
    if wardrobe_desc:
        chg["wardrobe_desc"] = wardrobe_desc
    if style_video:
        chg["style_video"] = True
    if style_ref:
        chg["style_ref"] = True
        slots.append("style_ref")
    if style:
        chg["style"] = style
    if extra:
        chg["extra"] = extra
    if keep_off:
        chg["keep"] = {k: False for k in ("motion", "camera", "rhythm",
                                          "background", "framing", "lighting")}
    if audio:
        chg["audio"] = audio
    p = edit_spec.compile_prompt(
        "volc", edit_spec.normalize(chg), model=M25,
        source_people=picked, frame_people=frame,
        desc_by_id={x["id"]: {"zh": x["desc_zh"], "en": ""} for x in frame},
        slots=slots, audio_ref=bool(audio),
        shot_cuts=cuts, shot_lines=lines, style_video=bool(style_video))
    return (name, p, frame, picked, slots, [x["id"] for x in picked])


