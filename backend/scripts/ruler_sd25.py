def c1_params(p, ctx):
    """`sd25-pe:76` 原则 7「参数分离」：画幅/总时长/分辨率/帧率/声音开关不写进 Prompt。

    🩸 只认**参数形态**（`16:9` / `1080p` / `30fps` / 「帧率」「分辨率」「画幅」）。
    「0-3 秒」这种时间轴是**创作内容**（指南 `:215` 明确支持），不算参数。
    """
    # 🩸 2026-10-29 变异测试抓到的真 bug：`\b` 在中文旁边**不成立** ——
    #   Python 的 `\w` 默认 Unicode，汉字算 word 字符，所以「输出1080p」里
    #   `1080` 前面没有词边界 → 正则从来不匹配。实测「输出30fps」也抓不到。
    #   改用「前一个字符不是 ASCII 字母数字」的显式断言。
    bad = []
    for pat, why in ((r"(?<![0-9A-Za-z])\d{1,2}\s*[:：]\s*\d{1,2}(?![0-9])", "画幅比例"),
                     (r"(?<![0-9A-Za-z])\d{3,4}\s*[pP](?![A-Za-z0-9])", "分辨率"),
                     (r"(?<![0-9A-Za-z])\d{1,3}\s*fps(?![A-Za-z0-9])", "帧率"),
                     (r"帧率|分辨率|画幅", "参数词"),
                     # 🩸 2026-10-28（2.5 标准补齐）：`:76` 列的是
                     # 「画幅、**总时长**、分辨率、帧率和**声音开关**」五项，
                     # 以前只判了前三项。注意「持续时长/时间轴」是**创作内容**
                     # （`:76` 同句说明 + 指南 `:215`），不能一起判。
                     (r"总时长|输出时长|成片时长|时长为\s*\d+\s*秒", "时长参数"),
                     (r"生成音频|声音开关|generate_audio|with_audio", "声音开关")):
        m = re.search(pat, p)
        if m:
            bad.append(f"{why}：「{m.group(0)}」")
    return bad


