def t5_duty(p, ctx):
    """`sd25-pe:567`【目标素材职责】每份素材一句「用于…，不采用…」（原则 3 `:72`）。

    🩸 只查**真的被用到的**素材：@视频1 是编辑母版，它有自己的【原视频职责】段，
    不该被要求写「不采用」。
    """
    # 🩸 2026-10-28：音频素材的职责行官方写在**独立段**【目标音频职责】
    #   （`sd25-pe:625-626` `@音频1用于<目标说话人或声音类别>的<…>，不采用<无关声音>。`），
    #   不在【目标素材职责】里。两条段都看 —— 这是认官方第二种写法，
    #   不是豁免：职责行缺失照样红。
    sec = _sec(p, "【目标素材职责】") + "\n" + _sec(p, "【目标音频职责】")
    # 同 `t1_sections` 的豁免：一份参考素材都没用时这一段可以省（`sd25-pe:324`）
    if not sec.strip():
        if not re.search(r"@(图片|音频)\s*\d+", p):
            return []
        return ["【目标素材职责】为空"]
    # 🩸 2026-10-28（素材引用保真章）：用户**自己在补充说明里写的** `@图片N`
    #   即使当前没有对应素材，官方也要求「最终 Prompt 保留相同引用形式和编号…
    #   不触发 Prompt 外的素材缺失说明」（`sd25-pe:916`）。它不是"我们发了却
    #   没交代"的素材，不该按缺职责判红 —— 调用方给 `ctx["materials"]`（这份
    #   Prompt 实际发出去的素材编号集合）时才启用这条豁免；没给就照旧全查。
    _mats = ctx.get("materials")
    used = set(re.findall(r"@(图片|视频|音频)\s*(\d+)", p))
    if _mats is not None:
        used = {x for x in used if f"@{x[0]}{x[1]}" in _mats}
    # 🩸 2026-10-28（分段一致性实测）：官方对"发了但这一段用不上"的素材给了
    #   **第二种交代方式** —— `:410`「只使用与当前故事和场景相关的素材；把实际
    #   可用但未分配职责的素材放进 `【未采用素材】`，逐个列出未采用编号并禁止
    #   激活」，示例 `:233`「@图片5、@图片6未参与本任务，不用于人物、场景、
    #   道具、动作或镜头」。这类素材**不该**有「用于…」职责行（有就等于这段
    #   要改它），所以不能按「没有职责行」判红。
    unused = _sec(p, "【未采用素材】")
    bad = []
    for kind, n in sorted(used):
        if kind == "视频" and n == "1":
            continue
        tag = f"@{kind}{n}"
        if tag not in sec:
            if tag in unused:
                continue
            bad.append(f"{tag} 没有职责行")
        elif re.search(re.escape(tag) + r"作为(首|尾)帧", sec):
            # 🩸 2026-10-28：官方 `:703`「固定首帧时必须**单独写出**
            #   `@图片N作为首帧。`」—— 首帧/尾帧是**官方指定的另一种写法**，
            #   本来就不带「不采用」。这不是豁免，是认第二种官方句式。
            continue
        elif not re.search(re.escape(tag) + r"[^。\n]*不采用", sec):
            bad.append(f"{tag} 的职责行没写「不采用…」")
    return bad


