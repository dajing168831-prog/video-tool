def _sec(p: str, name: str) -> str:
    """取某个【段】的正文（到下一个【为止）。"""
    i = p.find(name)
    if i < 0:
        return ""
    j = p.find("【", i + len(name))
    return p[i + len(name):j if j > 0 else len(p)]


def t1_sections(p, ctx):
    """`sd25-pe:559-576` 视频编辑五段齐全，且**顺序正确**。

    🩸 2026-10-26（2.5 穷举 E2 抓到）：`sd25-pe:324` 同时写着「选择下文对应
    模板，**只保留当前任务需要的段落**」。只改风格 / 只加补充说明这类任务
    **一份素材都不用**，硬要【目标素材职责】就是空段 —— 按 `:324` 允许省。
    所以：提示词里没有任何 `@图片N` / `@音频N` 时，这一段可以不出现；
    一旦用了素材，五段里这一段就必须在。
    """
    need = list(SEC_EDIT)
    if not re.search(r"@(图片|音频)\s*\d+", p):
        need = [s for s in need if s != "【目标素材职责】"]
    pos = [p.find(s) for s in need]
    miss = [s for s, i in zip(need, pos) if i < 0]
    if miss:
        return [f"缺段 {''.join(miss)}"]
    if pos != sorted(pos):
        return ["五段顺序乱了"]
    return []


