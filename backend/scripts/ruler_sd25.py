def _subsets(n: int):
    from itertools import combinations
    out = []
    for k in range(1, n + 1):
        out.extend(combinations(range(n), k))
    return out


_IMG_SLOTS = ("person", "person2", "person3", "person4", "product", "scene",
              "style_ref")


def _img_slot_count(slots) -> int:
    return sum(1 for s in slots if s in _IMG_SLOTS or s.startswith("wardrobe"))


#: 台词前 16 字内必须出现的"说话人/说话动作"（官方 `:869` 的台词语法要求）。
_SPEECH_HEAD = re.compile(
    r"(?:说道|说|喊道|喊|问道|问|答道|答|念道|念|吼道|吼|骂道|骂|告诉|"
    r"said|says|say|asked|asks|shouted|yelled|told|whispered|replied)", re.I)


def _struct(p: str, slots) -> list[str]:
    """结构判据（与 2.0 的 A1–A4 同口径）：形状不对就是破口。"""
    bad = []
    # 与 `t1_sections` 同一条豁免：一份素材都没用时【目标素材职责】可以省
    # （`sd25-pe:324`「只保留当前任务需要的段落」）。
    need = SEC_EDIT
    if not re.search(r"@(图片|音频)\s*\d+", p):
        need = tuple(s for s in SEC_EDIT if s != "【目标素材职责】")
    miss = [s for s in need if s not in p]
    if miss:
        bad.append("缺段 " + "".join(miss))
    else:
        pos = [p.find(s) for s in need]
        if pos != sorted(pos):
            bad.append("五段顺序乱")
    # 🩸 2026-10-28（E12 参考系自证）：**每段只能出现一次**。
    #   官方模板 `sd25-pe:559-576` 是五段、每段一个标题。用户自由文本
    #   （补充说明 / 换装描述）里写「【编辑目标】」实测能塞出第二个同名段，
    #   而上面只查"在不在、顺序对不对"—— 段数从 1 变 2 照样判绿。
    #   这是**唯一**能抓到"结构被伪造"的判据，不能只靠编译器那头兜。
    dup = [s for s in SEC_EDIT if p.count(s) > 1]
    if dup:
        bad.append("段重复 " + "".join(dup))
    if "<" in p or ">" in p:
        bad.append("残留尖括号占位符/主体名")
    # 🩸 2026-10-29（D72）：【编辑目标】里两处 `<原对象>` **不许一字不差** ——
    #   官方模板 `sd25-pe:559-575` 要的是具体原对象；两句一样，模型分不清换谁。
    #   真人盘点 `686dc484` 8 人场里 4 位都以「黑人男性，」开头，本条当场抓到。
    # 🩸 字母后缀「（目标人物A）」只是换个叫法、**不提供画面里的定位**，
    #   比较前先剥掉 —— 否则「黑人男性（目标人物A）」和「…B」会被判成互异。
    _objs = [re.sub(r"（目标人物[A-Z]）$", "", m.group(1).strip()).strip()
             for m in re.finditer(r"把(.{1,40}?)替换为", p)]
    for _x in sorted({x for x in _objs if _objs.count(x) > 1}):
        bad.append(f"两处原对象一字不差：「{_x}」（换谁分不清）")
    # 🩸 2026-10-28（E13 参考系自证）：`{}` 是台词标记（`:867`），半截花括号
    #   一定是自由文本漏洗进来的。合法产出永远成对，所以这条零误伤。
    #   ⚠️ **只抓单边**：`{旁白}` 这种成对的误用抓不到 —— 我们自己的 `extra`
    #   引号转换也会往【编辑目标】里写 `{}`，判"位置对不对"会误伤。编译器那头
    #   的清洗是主防线，判据只是第二道，这一形状记在台账里当已知缺口。
    if p.count("{") != p.count("}"):
        bad.append("花括号不成对（台词标记被切断）")
    # 🩸 2026-10-28（E13 收尾，补掉"成对误用抓不到"那个缺口）：
    #   官方 `:869` 的台词语法是「语言 + 可选地区变体 + 表达方式 + **说话人** + {台词}」
    #   —— 台词前面一定有说话人/说话动作。孤零零贴在名词后面的 `{旁白}`
    #   不是台词，是自由文本里的符号漏进来了（`:880` 一符两用）。
    #   合法形态（`@图片1中的人物说{…}` / `…使用英语说道{…}`）都带说话标记。
    for _m in re.finditer(r"\{[^{}\n]{1,60}\}", p):
        _ls = p.rfind("\n", 0, _m.start()) + 1
        _head = p[_ls:_m.start()]
        # 整行只有台词 = 说话人未知时不指名（`video_edit._assign_speakers`：
        # 「两个证据都没有的句子不标」）—— 这是**合法**形态，不是漏标。
        if not _head.strip():
            continue
        if not _SPEECH_HEAD.search(_head):
            bad.append(f"台词 {_m.group(0)} 前面没有说话人")
            break
    nums = [int(x) for x in re.findall(r"@图片\s*(\d+)", p)]
    cap = _img_slot_count(slots)
    if nums and max(nums) > cap:
        bad.append(f"引用了@图片{max(nums)}，但只发了 {cap} 张图")
    return bad


def _judge(rows, title: str, *, genre="tpl", expect=None) -> tuple[int, int, int]:
    """跑一组，返回 (破口数, 闸拦数, 组合数)。

    🩸 口径与 2.0 一致：**尺子红 / 结构失败 / 崩溃** = 破口；
    出片前的闸拦住 = 正确行为，单列不计数（但不能悄悄算绿）。
    """
    from app.services import video_edit

    n_bad = n_gate = 0
    seen = set()
    for name, p, frame, picked, slots, ids in rows:
        if p in seen:
            pass
        seen.add(p)
        vs = check(p, ctx_for(p, frame, genre))
        red = [v for v in vs if v[1] == "红"]
        bad = _struct(p, slots) if genre == "tpl" else []
        if red or bad:
            blocked, why = False, ""
            try:
                video_edit.require_identifiable_volc25({"people": frame},
                                                       slots, ids)
            except video_edit.EditError as e:
                blocked, why = True, str(e).split("。")[0]
            if blocked:
                n_gate += 1
                continue
            n_bad += 1
            print(f"\n  [破口] {name}")
            for v in red:
                print(f"      {v[1]} {v[0]} {v[2]} ← {v[3]}｜{str(v[4][0])[:70]}")
            for b in bad:
                print(f"      ✗ {b}")
            print(f"         {p[:140]}")
    if expect is not None and len(rows) != expect:
        print(f"  ✗ {title}：跑了 {len(rows)} 条，期望 {expect} 条（空集不算通过）")
        n_bad += 1
    print(f"  {'✅' if n_bad == 0 else '❌'} {title}：{len(rows)} 条"
          f"（破口 {n_bad} / 闸拦 {n_gate} / 去重后 {len(seen)} 种输出）")
    return n_bad, n_gate, len(rows)


