#: 产物里的词 → 槽位类型（风格槽的官方写法是「整体画面的色调、光影和质感」）
_SLOT_WORDS = (("人物", "人物"), ("服装", "服装"), ("产品", "产品"),
               ("场景", "场景"), ("风格", "风格"), ("整体画面", "风格"),
               ("色调", "风格"))
_SLOT_KIND = {"product": "产品", "scene": "场景", "style_ref": "风格"}


def _slot_kind(slot: str) -> str:
    """槽位名 → 素材类型（`person3`…`person16` / `wardrobe2`… 都要认）。"""
    if slot.startswith("person"):
        return "人物"
    if slot.startswith("wardrobe"):
        return "服装"
    return _SLOT_KIND.get(slot, "?")


def _slotmap_bad(p: str, perm) -> list[str]:
    """`@图片N` 的编号有没有跟 `slots[N-1]` 对上（E14 的判定本体）。

    抽成纯函数是为了能**拿已知坏样本自证**（把两行职责的编号对调 → 必须报错），
    否则这条判据哑火和全绿分不开。
    """
    want = {i + 1: _slot_kind(s) for i, s in enumerate(perm)}

    def _say(text: str) -> str:
        for w, v in _SLOT_WORDS:
            if w in text:
                return v
        return "?" + text[:12]

    out = []
    sec = p.split("【目标素材职责】")[-1].split("【编辑对象与范围】")[0]
    got = {int(m.group(1)): _say(m.group(2))
           for m in re.finditer(r"@图片\s*(\d+)用于([^，。\n]*)", sec)}
    if got != want:
        out.append(f"职责行错位：实际 {dict(sorted(got.items()))} "
                   f"应为 {dict(sorted(want.items()))}")
        return out
    goal = p.split("【原视频职责】")[0]
    for m in re.finditer(r"@图片\s*(\d+)(?:中的|的)(人物|产品|场景|服装|风格)", goal):
        num, what = int(m.group(1)), m.group(2)
        if want.get(num) != what:
            out.append(f"目标句绑错：@图片{num} 被说成「{what}」，"
                       f"实际是「{want.get(num)}」")
            break
    return out


