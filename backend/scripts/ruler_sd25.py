def calib() -> int:
    rows = official_cases()
    n_red = 0
    stats: dict[str, list[int]] = {}
    for name, g, p, extra in rows:
        _ctx = ctx_for(p, genre=g)
        _ctx.update(extra)
        vs = check(p, _ctx)
        n_app = sum(1 for r in RULES if g in r[5])
        st = stats.setdefault(g, [0, 0, 0])
        st[0] += 1
        st[1] += n_app
        red = [v for v in vs if v[1] == "红"]
        st[2] += len(red)
        n_red += len(red)
        if vs:
            print(f"\n[{g}] {name}（适用 {n_app}/{len(RULES)} 条）")
            for v in vs:
                print(f"   {v[1]} {v[0]} {v[2]} ← {v[3]}｜{v[4][0][:70]}")
    for g, (n, app, red) in sorted(stats.items()):
        print(f"  {g}: {n} 条示例 / 累计适用 {app} 条规则 / 红 {red}")
    print(f"\n官方语料校准：{len(rows)} 条，红 {n_red} 条"
          f"（{sum(s[1] for s in stats.values())} 条规则-示例判定）")
    return 0 if n_red == 0 else 1


