    print(f"\n多变数扫描（2.5）：{len(rows)} 个组合（零模型调用）")
    print(f"  破口：尺子红 {n_red} 条 / 结构判据失败 {n_assert} 条")
    if per:
        print("  按规则：" + "、".join(f"{k}×{v}" for k, v in sorted(per.items())))
    return 0 if (n_red == 0 and n_assert == 0) else 1


