def genre_of(p: str) -> str:
    """官方示例属于哪类任务：`edit` 编辑 / `extend` 延长·补全 / `gen` 参考生成。

    判据按官方章节的推荐句式来（sd20-guide:17-54）：
      · 参考生成 = 「参考<图片N>中的<主体>，生成…」→ `视频N` 只是风格/动作来源；
      · 编辑     = 「严格编辑<视频N>，将其中的…」/ 增加·删除元素；
      · 延长/补全 = 「向前延长<视频N>」/「<视频1> + 过渡 + 接<视频2>」。
    """
    if re.search(r"向前延长|向后延长|延长\s*`?@?视频|接\s*`?@?视频\s*\d", p):
        return "extend"
    if re.search(r"严格编辑", p):
        return "edit"
    if re.search(r"替换|修改为|改成|替换成|添加|删除|清除|去掉|抹除", p) \
            and re.search(r"@?视频\s*\d", p):
        return "edit"
    if re.search(r"参考[^，。；]{0,20}视频\s*\d", p):
        return "gen"
    if not re.search(r"@?视频\s*\d", p):
        return "gen"
    # 有 @视频N、没有任何编辑动词、也不是"接视频"句式 → 按延长/补全算
    return "extend"


def check(prompt: str, ctx: dict | None = None) -> list[tuple]:
    ctx = ctx or {}
    genre = ctx.get("genre") or "edit"
    out = []
    for rid, sev, name, src, fn in RULES:
        if genre not in RULE_GENRES.get(rid, {"edit", "extend", "gen"}):
            continue
        hits = fn(prompt, ctx)
        if hits:
            out.append((rid, sev, name, src, hits))
    return out


def ctx_for(prompt: str, people: list | None = None) -> dict:
    """`n_targets` = 提示词里**点名了几个不同的人**（几种 `@图片N中的人物`）。

    🩸 以前只数 `替换为@图片N中的人物`。这有两种写法，只认一种就会让判据
    **对空集恒真**：现行写法是「将@图片1中的人物定义为<主体1>…将其中的<主体2>
    替换为<主体1>」，宾语换成标签后替换位一个图号都没有 → n_targets=0 →
    R05 说什么都不响，好样本"通过"是空的。
    现在按**整句正文**数（先剔掉职责句：面部特征/妆造是同一张图的复用），
    两种写法都能数出来；`<主体>` 在不在由规则自己判。
    """
    body = re.sub(r"面部特征[^；。]*|妆造[^；。]*", "", prompt)
    pics = set(re.findall(PIC + r"\s*中的人物", body))
    return {"people": people or [], "n_targets": len(pics)}


