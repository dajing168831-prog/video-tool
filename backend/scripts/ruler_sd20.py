def _d1_cases() -> list:
    """D1 换人主路径：人数 × 方位 × **所有非空勾选子集** × 参考图有无外观描述。

    🩸 2026-10-26：`body` 那一维（单图 / 大头照+全身照）已删 —— 一个人只有一张图
    （台账 D48），组合数因此从 156 降到 78。
    🩸 2026-10-26 19:xx **补回一维 `look`**：生产每条换人任务都带
    `subject_look`（`subject_desc.json`），而这一维此前**一次都没扫过** ——
    "参考图里那个人有没有被定义成主体"这个最要命的差别，尺子全程看不见。
    组合数 78 → 156。
    """
    import itertools
    rows = []
    for n in (1, 2, 3, 4):
        for pos in ("unique", "clash", "missing"):
            subs = [c for r in range(1, n + 1)
                    for c in itertools.combinations(range(n), r)]
            for look in (False, True):
                for picks in subs:
                    rows.append(_sd_case(
                        f"D1 n={n} pos={pos} picks={picks}"
                        f"{' look' if look else ''}",
                        n=n, pos=pos, picks=picks, look=look))
    return rows


