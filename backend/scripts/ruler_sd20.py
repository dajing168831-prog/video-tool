def official_prompts() -> list[tuple[int, str]]:
    """把指南附录里所有 `**[提示词]**` 后面的正文抽出来。"""
    L = GUIDE.read_text(encoding="utf-8").split("\n")
    out = []
    for i, line in enumerate(L):
        if line.strip() != "**[提示词]**":
            continue
        buf = []
        j = i + 1
        while j < len(L):
            s = L[j].strip()
            if not s:
                if buf:
                    break
                j += 1
                continue
            if s.startswith("**[") or s.startswith("![") or s.startswith("---"):
                break
            buf.append(s)
            j += 1
        if buf:
            out.append((i + 1, " ".join(buf)))
    return out


def calib() -> int:
    """拿官方自己的提示词案例量这把尺子：**一条红都不许出**。

    🩸 按体裁分别量：编辑 / 延长·补全 / 参考生成 三种任务的句式要求不同，
    混在一起量会把参考任务的合法写法判成红（2026-10-25 第一版就是这么错的：
    24 条里 13 条红，全是「参考<视频N>」的生成示例被编辑任务的规则打中）。
    每条结论都带 **N/M**（在这条示例上真正适用的规则条数），不许拿"空集通过"充数。
    """
    rows = official_prompts()
    n_red = 0
    stats: dict[str, list[int]] = {}
    for ln, p in rows:
        g = genre_of(p)
        ctx = ctx_for(p)
        ctx["genre"] = g
        vs = check(p, ctx)
        n_app = sum(1 for rid in (r[0] for r in RULES)
                    if g in RULE_GENRES.get(rid, {"edit", "extend", "gen"}))
        st = stats.setdefault(g, [0, 0, 0])   # 条数 / 适用规则总数 / 红
        st[0] += 1
        st[1] += n_app
        red = [v for v in vs if v[1] == "红"]
        st[2] += len(red)
        n_red += len(red)
        if vs:
            print(f"\n[sd20-guide:{ln}][{g}] {p[:60]}…（适用 {n_app}/{len(RULES)} 条）")
            for v in vs:
                mark = "红" if v[1] == "红" else "黄"
                print(f"   {mark} {v[0]} {v[2]} ← {v[4][0] if v[4] else ''}")
    for g, (n, app, red) in sorted(stats.items()):
        print(f"  {g}: {n} 条示例 / 累计适用 {app} 条规则 / 红 {red}")
    print(f"\n官方示例校准：{len(rows)} 条，红 {n_red} 条"
          f"（{sum(s[1] for s in stats.values())} 条规则-示例判定）")
    return 0 if n_red == 0 else 1


