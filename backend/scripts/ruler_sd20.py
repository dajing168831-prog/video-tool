def r05_multi_label(p, ctx):
    """官方 `sd20-guide:109`：「当视频中存在多个主体时，**需要**分别定义，并使用标签区分。」

    🩸 2026-10-30 降级（红 → 黄）并放宽手段（主人拍板：「有没有必要说主体 →
    就这样来」）：
      · 原文是「需要」不是「必须」，而**官方自己的编辑示例一个标签都没有**
        （`sd20-guide:941`「将视频1中的香水替换成图片1中的面霜」）——
        按本尺子的分档原则（红 = 官方明令 **且官方自己的示例也遵守**），
        它本来就该是黄。
      · 「指代不混乱」这个**意图**照样守：点名 ≥2 个换人对象时，要么用 `<主体N>`，
        要么每个替换句的宾语各自带一个能指认的短语；**两句都写裸「人物」不行**。
    """
    n = ctx.get("n_targets") or 0
    if n < 2 or "<主体" in p:
        return []
    objs = [x.strip() for x in re.findall(r"将其中的(.{1,40}?)替换为", p)]
    vague = [o for o in objs if o in ("人物", "")]
    if vague or len(objs) < n:
        return [f"点名 {n} 个换人对象，既无 <主体N>，宾语也指认不了"]
    return []


def r06_label_feature(p, ctx):
    """标签定义要能指认出是谁。**图片侧允许零特征，原片侧从严**。

    🩸 2026-10-27（主人拍板）：以前这条对「将@图片1中的人物定义为<主体1>」报黄，
    理由是 `:95` 要 2–3 个静态特征。回源看两处原文，那个理由站不住：
      · `sd2-pe:15`「**多主体场景或需复用**：先定义 将@图片N中的[2-3个稳定静态特征]
        定义为<主体N>」—— 要求带特征的前提是**一张图里有多个主体**；
      · `sd2-pe:137`「一次性绑定全部主体：`<主体N>@图片N` **或** 将@图片N中的
        [2-3个静态特征]定义为<主体N>」—— 官方自己用「或」给了两种写法。
    而官方标准示例 `20 双人全换` 原句就是「将@图片1中的人物定义为<主体1>」
    （一张图一个人，没有歧义）。⇒ 图片侧放行。

    原片侧**保持从严**：画面里往往真有好几个人（`:107` 要求分别定义），
    只写「@视频1中的人物」等于没指认，换错人。这一档也防回退 ——
    以后谁把方位/特征逻辑删了，它立刻响。
    （"合影要特征"这一档系统判不了：我们只盘点原视频，不盘点用户传的参考图。）
    """
    bad = []
    for m in re.finditer(r"将([^。；，]{0,30}?)定义为\s*<主体\s*\d+>", p):
        body = m.group(1).strip()
        # 图片侧：零特征放行（见 docstring）
        if re.fullmatch(r"@?图片\s*\d+(、@?图片\s*\d+)*中的(人物|角色)", body):
            continue
        # 原片侧：光写「人物」= 没指认
        if re.fullmatch(r"@?视频\s*\d+中(的)?(人物|角色)", body):
            bad.append(m.group(0))
    return bad


def r07_label_consistency(p, ctx):
    """官方 :119 已定义标签后，每次提到都应使用同一标签。

    🩸 2026-10-25 扩到**所有改动句**，不只「替换为」：
    `--sweep` 的「2 人·同时换装」组抓到「将其中的体型偏胖的男子，黑色头发束成
    发髻，身着浅青绿色古装的**服装**换成@图片2中的服装」—— 前半句刚把这个人
    绑成 `<主体2>`，后半句又改叫「体型偏胖的男子…古装」，同一句提示词里两套指法
    （官方 `:110`「后续描述中需持续使用对应标签」）。
    只判**指人**的宾语：`背景` / `场景` / `产品` 这些不是人，用不着标签。
    """
    if "<主体" not in p:
        return []
    # 🩸 2026-10-28（当前产出实测，零成本矩阵 7/7 素材）：这条以前把**没被定义过
    #   的人**也判红 —— 只要句子里出现「将其中的X的服装换成…」而 X 不是标签就报。
    #   实际产物是「只换 P1 的人、只换 P2 的衣服」：P2 从头到尾没绑过 `<主体N>`
    #   （官方 `:119` 约束的是**已定义**主体），这句话是官方 `:39`
    #   「将其中的<原特征>修改为<新特征>」的合法写法，却天天报红 —— 红项一多，
    #   真正的回退就淹没在里面（[[vacuous-truth-false-green]] 的反面：假红同样有毒）。
    #   ⇒ 判据按自己的出处收紧：**先从定义句取出原片侧已绑标签的那些人**，
    #     宾语指向其中某一位时才叫"同一人两个名字"。
    defined = [m.group(1).strip() for m in re.finditer(
        r"将\s*(?:@视频\d+|视频\d+)\s*中\s*(.{1,40}?)\s*定义为\s*<主体\d+>", p)]
    bad = []
    # 🩸 宾语里**允许有逗号**：旧换装句的宾语就是一整段外观描述
    # （「体型偏胖的男子，黑色头发束成发髻，身着浅青绿色古装的服装」）。
    # 第一版把逗号排除了，坏样本因此哑火（非贪婪 + 停在第一个动词上即可）。
    for m in re.finditer(r"将其中的\s*(.{1,60}?)\s*(?:完整)?(?:替换为|换成|改成|修改为)", p):
        obj = m.group(1).strip()
        if obj.startswith("<主体"):
            continue
        personish = ("人物" in obj or "的服装" in obj
                     or re.search(r"(男子|女子|少年|老者|女孩|男孩|老人)$", obj))
        if not personish:
            continue
        # 只见于定义句里、没有在正文里复用标签的那个人才是违规
        if not any(d and (d in obj or obj in d) for d in defined):
            continue
        bad.append(m.group(0))

    # 🩸 2026-10-29 变异测试抓到的盲区：上面只查「换装/替换」句的宾语。
    #   `将@视频1中体型偏胖的男子定义为<主体3>` 之后，正文又写「体型偏胖的男子走向门口」
    #   —— 同一人两套指法，旧判据完全看不见（变异 16 条里唯一漏网的）。
    #   出处同一条：`sd20-guide:119`「后续描述中需持续使用对应标签」。
    #   ⚠️ 只认**定义句里原样给过的那段描述**；换成全新的描述（如"那个蓝衣服的男生"）
    #      尺子无从匹配 —— 那是模型端的语义混淆，不是文本可机械检的。
    for m in re.finditer(
            r"将\s*(?:@视频\d+|视频\d+)\s*中\s*(.{2,40}?)\s*定义为\s*<主体(\d+)>", p):
        desc, lab = m.group(1).strip(), m.group(2)
        if len(desc) < 4:
            continue
        for mm in re.finditer(re.escape(desc), p):
            if m.start() <= mm.start() < m.end():
                continue                      # 定义句本身
            tail = p[mm.end():mm.end() + 12]
            if "<主体" not in tail and "定义为" not in tail:
                bad.append(f"「{desc[:16]}…」已定义为<主体{lab}>，正文又改用描述指代")
                break
    return bad


def r08_redundancy(p, ctx):
    """官方 :121 避免冗余：同一句里同一图号出现 ≥3 次。

    🩸 按 **句号** 切，不按分号：冗余往往横跨分号
    （「替换为@图片1中的人物；面部特征参考@图片1中的人物，妆造参考@图片1中的人物」），
    按分号切就只剩 1 次 + 2 次，永远不响 —— 第一版就是在这里哑火的。
    """
    bad = []
    for cl in p.split("。"):
        pics = re.findall(PIC, cl)
        for n in set(pics):
            if pics.count(n) >= 3:
                bad.append(f"@图片{n}×{pics.count(n)}：{cl.strip()[:40]}")
    return bad


def r09_object_unique(p, ctx):
    """sd2-pe:72 多人未指明谁在左/右 = 病灶。

    🩸 2026-10-28 扩到**所有改动句**（不只换人）：当前产出里换装一直走
    「将其中的<谁>的服装换成@图片N中的服装」。换装目标和换人名单是两张表，
    "只换装不换人"时一个人都没绑标签 ⇒ 全靠这句宾语指人。零成本矩阵实测
    （`2f1f26d8` 只换两人衣服）旧版产物是**两句一模一样**的
    「将其中的男性的服装换成…」，模型只能猜谁换哪套 —— 钱照扣、结果随机。
    同一句法、同一个病灶（没说清是谁），所以并入本规则而不是另立一条。
    """
    ppl = ctx.get("people") or []
    if len(ppl) < 2:
        return []
    pos_count: dict[str, int] = {}
    for x in ppl:
        k = POS_ZH.get(str(x.get("position") or ""), "")
        if k:
            pos_count[k] = pos_count.get(k, 0) + 1
    bad = []
    for m in re.finditer(r"将其中的\s*(.{0,26}?)\s*(?:完整)?(?:替换为|换成|改成|修改为)", p):
        obj = m.group(1).strip()
        # 纯泛称（方位/特征一律没有）在 ≥2 人画面里没有唯一解。
        # 换装句的宾语是「<谁>的服装」，把后缀摘掉再看剩下的是不是纯泛称。
        core = obj[:-len("的服装")] if obj.endswith("的服装") else obj
        if re.fullmatch(r"人物|男性|女性|男子|女子|男人|女人|男士|女士", core):
            bad.append(f"宾语=「{obj}」，画面 ≥2 人时无唯一解")
        for k, n in pos_count.items():
            if obj == f"{k}的人物" and n > 1:
                bad.append(f"宾语=「{obj}」，但{k}站着 {n} 个人")
    return bad


