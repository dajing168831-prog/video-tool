# 这条判据反过来：**编译器读的每个参数，必须至少有一个用例把它设成非空**。

# 2.0 上「永远为空」是有官方/台账依据的，逐条写明；不写理由的一律算破口。
COVER_EMPTY_OK = {
    "boundary_pic": "2.0 不带边界帧（`boundary_allowed` 关着；边界帧是 2.5/H3 的链条）",
}


def coverage() -> int:
    from app.services.models import volc20_compile

    seen: dict[str, int] = {}
    orig = volc20_compile._volc

    def spy(spec, c, idx, **kw):
        for k, v in kw.items():
            if v not in (None, "", False, 0, [], {}):
                seen[k] = seen.get(k, 0) + 1
        return orig(spec, c, idx, **kw)

    volc20_compile._volc = spy
    try:
        for fn in (_d1_cases, _d2_cases, _d3_cases, _d4_cases, _d7_cases,
                   current_cases):
            for row in fn():
                _ = row
    finally:
        volc20_compile._volc = orig
    # 引擎里 `compile` 走的是模块函数引用，直接调一次确认接线没断
    if not seen:
        print("🔴 拦截不到任何实参 —— 接线断了，覆盖自证无效")
        return 1

    import inspect
    params = [p for p in inspect.signature(
        volc20_compile._volc).parameters if p not in ("spec", "c", "idx")]
    bad = []
    print("=" * 78)
    print("覆盖自证：编译器读的每个参数，至少被一个用例设成非空")
    print("（这一条只证明「参数进得来」；**有没有效果**由 D9 消融表逐条判，别拿它当验收）")
    for p in params:
        n = seen.get(p, 0)
        if n:
            print(f"  ok   {p:<16} {n} 次非空")
        elif p in COVER_EMPTY_OK:
            print(f"  ok*  {p:<16} 2.0 永远为空 —— {COVER_EMPTY_OK[p]}")
        else:
            bad.append(p)
            print(f"  🔴  {p:<16} **一次都没被设成非空** —— 尺子量不到这条路")
    print(f"\n覆盖：{len(params) - len(bad)}/{len(params)}")
    return 1 if bad else 0


def real_cases() -> int:
    """拿**真实付费发出去**的提示词量尺子（`data/clone/*/render/*/triage/request_*.json`）。

    🩸 2026-10-28（主人：「**提示词产出有误直接生成失败而不是被拒！这才是最可怕的
    钱花了没达到想要的**」）：`--exhaustive` / `--sweep` 量的都是**我们构造**的形状，
    构造得再全也是"我想得到的"。真实发出去的那些句子，是钱已经花掉的样本 ——
    拿它们量尺子，才知道尺子有没有牙齿、以及我们历史上真正白花过哪些钱。

    输出是**人审清单**，不是"必须 0"：这些快照是历史，命中的是历史缺陷。
    真正该盯的是**新出现的命中**（改代码后重跑，对比这份清单）。
    """
    import json
    from collections import Counter
    from pathlib import Path as _P

    root = _P(__file__).resolve().parents[1] / "data" / "clone"
    files = sorted(root.glob("*/render/*/triage/request_*.json"))
    hits: Counter = Counter()
    where: dict[str, list] = {}
    checked = 0
    for f in files:
        try:
            p = json.loads(f.read_text(encoding="utf-8")).get("prompt") or ""
        except Exception:  # noqa: BLE001
            continue
        if not p:
            continue
        checked += 1
        ctx = ctx_for(p)
        for rid, _lv, title, _src, fn in RULES:
            g = RULE_GENRES.get(rid)
            if g and genre_of(p) not in g:
                continue
            try:
                bad = fn(p, ctx) or []
            except Exception as e:  # noqa: BLE001
                bad = [f"(规则崩了) {e}"]
            if bad:
                hits[rid] += 1
                where.setdefault(rid, []).append(
                    (f.parent.parent.parent.name[:8], str(bad[0])[:150]))
    print(f"真实付费请求快照：{checked} 份（{root}）\n")
    if not hits:
        print("一条都没响 —— 要么真干净，要么尺子没牙齿（先看 --probes）。")
        return 0
    for rid, n in hits.most_common():
        lv = next(l for r, l, *_ in RULES if r == rid)
        ti = next(t for r, l, t, *_ in RULES if r == rid)
        print(f"{rid} [{lv}] {n} 份  {ti}")
        for w, ev in where[rid][:3]:
            print(f"    [{w}] {ev}")
    print("\n🩸 这些是**历史**样本：命中的是当时真花掉的钱。改代码后重跑，"
          "看清单有没有**新增** —— 新增才是回退。")
    return 0


