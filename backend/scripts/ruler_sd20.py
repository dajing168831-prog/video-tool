def _d7_consistency() -> tuple[int, int]:
    """三档型号编出来的提示词必须**逐字相同**（差一个字就说明规格串了）。"""
    groups: dict[str, dict[str, str]] = {}
    for name, p, *_ in _d7_cases():
        tag = name.split("型号=")[1].split(" ")[0]
        label = name.split(" ", 2)[-1]
        groups.setdefault(label, {})[tag] = p
    ok = total = 0
    for label, got in groups.items():
        total += 1
        vals = set(got.values())
        if len(vals) == 1:
            ok += 1
        else:
            print(f"\n  🔴 D7 {label}：三档不一致")
            for tag, p in got.items():
                print(f"      [{tag}] {p[:110]}")
    print(f"\n三档型号一致性：{ok}/{total}")
    return ok, total


