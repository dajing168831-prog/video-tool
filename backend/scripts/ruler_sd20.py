def _judge_rows(rows, title: str, *, expect: int | None = None,
                show_all: bool = False, max_show: int = 40) -> int:
    """一组组合的公共判据：红 + 结构失败 + 崩溃 = 破口；闸拦住 = 覆盖但不计破口。

    🩸 出片前的闸（`video_edit.require_identifiable_volc20`）也算在内：
    有些输入本来就无解（盘点对这个人一个字都没给），编译器必然写出
    「将其中的**人物**替换为…」。这时正确的行为是**在花钱前拦住**，
    所以"闸拦住"记成被覆盖，不计破口 —— 但必须单独列出来，
    不许把它悄悄算成绿灯。
    🩸 **空集不算通过**：`expect` 给了就必须对上，`0/0` 记失败。
    """
    from app.services import video_edit

    n_red = n_assert = n_blocked = n_boom = 0
    per_rule: dict[str, int] = {}
    bad_rows: list[str] = []
    blocked_names: list[str] = []
    for name, p, frame, picked, slots, ids in rows:
        try:
            vs = check(p, ctx_for(p, frame))
            bad = _sd_invariants(p, frame, picked)
        except Exception as e:                       # noqa: BLE001
            n_boom += 1
            bad_rows.append(f"\n  [崩] {name} —— 判据自身抛错：{type(e).__name__}: {e}")
            continue
        red = [v for v in vs if v[1] == "红"]
        blocked, why = False, ""
        if red or bad:
            try:
                # 🩸 2026-10-29（D70）：闸要按**生产**那把尺判 —— 适配器
                #   （`models/volc20.py:_gate`）传的是 `sd20_locator` +
                #   `sd20_multi_locator`。这里不传，量的是另一个闸：
                #   D70 那一格会"闸放行"，于是被算成破口/假绿。
                from app.services.models.volc20_compile import (
                    sd20_locator, sd20_multi_locator)
                video_edit.require_identifiable_volc20(
                    {"people": frame}, slots, ids,
                    locator=sd20_locator, locator_multi=sd20_multi_locator)
            except video_edit.EditError as e:
                blocked, why = True, str(e).split("。")[0]
            except Exception:                        # noqa: BLE001
                # 闸自己崩了不是"拦住"——必须报出来
                n_boom += 1
                bad_rows.append(f"\n  [崩] {name} —— 出片前闸抛错")
                continue
        if blocked:
            n_blocked += 1
            blocked_names.append(name)
            continue
        n_red += len(red)
        n_assert += len(bad)
        for v in red:
            per_rule[v[0]] = per_rule.get(v[0], 0) + 1
        if red or bad:
            lines = [f"\n  [{'红' if red else '黄'}] {name}"]
            for v in red:
                lines.append(f"      {v[1]} {v[0]} {v[2]}  ← {v[3]}")
                lines.append(f"         证据：{str(v[4][0])[:90]}")
            for a in bad:
                lines.append(f"      ✗ {a}")
            lines.append(f"         提示词：{p[:150]}")
            bad_rows.append("\n".join(lines))

    print("=" * 78)
    print(title)
    if show_all:
        for s in bad_rows:
            print(s)
    else:
        for s in bad_rows[:max_show]:
            print(s)
        if len(bad_rows) > max_show:
            print(f"\n  …另有 {len(bad_rows) - max_show} 个破口未逐条打印")
    if blocked_names:
        print(f"\n  出片前被闸拦住 {n_blocked} 个（不是破口）：")
        for nm in blocked_names[:10]:
            print(f"      · {nm}")
        if len(blocked_names) > 10:
            print(f"      …另有 {len(blocked_names) - 10} 个")

    got = len(rows) + n_boom
    ok_count = (got == expect) if expect is not None else (got > 0)
    print(f"\n{title}")
    print(f"  组合数：{got}" + (f"（期望 {expect}）" if expect is not None else ""))
    print(f"  破口：尺子红 {n_red} 条 / 结构判据失败 {n_assert} 条 / 崩溃 {n_boom} 条"
          f"｜闸拦住 {n_blocked} 个")
    if per_rule:
        print("  按规则：" + "、".join(f"{k}×{v}" for k, v in sorted(per_rule.items())))
    if not ok_count:
        print(f"  🔴 组合数对不上：实际 {got} / 期望 {expect} —— 穷举没跑全，结论作废")
    return 0 if (n_red == 0 and n_assert == 0 and n_boom == 0 and ok_count) else 1


def sweep() -> int:
    return _judge_rows(sweep_cases(), "多变数扫描（手工编排的生产形状）")


