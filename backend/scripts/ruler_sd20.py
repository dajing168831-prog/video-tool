def _d15_indistinct() -> list[tuple[str, bool, str]]:
    """D15 描述完全相同 × 方位状态 —— 编译器与闸必须**同一把尺**。

    真实场景：同框几个人都留短发、都穿黑衣，盘点描述抹平了差异。这时
      · 方位各不相同 → 编译器写得出「画面左侧/中央/右侧」，闸就该放行；
      · 方位也撞车/缺失 → 编译器只能写出三句一模一样的指认，闸必须拦。
    判据是**一致性**，不是单向：`可区分 == 闸放行`。任一边错都算红。

    🩸 这条的口径来源：`test_edit_spec_sd20.py` 里那句「闸只做一件事：判编译器
    到底写不写得出能区分的一句，**不能比编译器更严**（那会拦掉好样本）」。
    """
    from app.services import edit_spec as _es
    from app.services import video_edit as _ve

    def _gate(people, ids):
        # 🩸 2026-10-29（D70）：这条判据的前提就是「闸与编译器同一把尺」——
        #   不传定位词 = 量的是另一个闸（旧判据只看描述互不互异）。
        from app.services.models.volc20_compile import (
            sd20_locator, sd20_multi_locator)
        try:
            _ve.require_identifiable_volc20({"people": people},
                                            ["person", "person2"], ids,
                                            locator=sd20_locator,
                                            locator_multi=sd20_multi_locator)
            return "pass"
        except _ve.EditError:
            return "block"

    def _ok(separable: bool, g: str) -> bool:
        return (separable and g == "pass") or ((not separable) and g == "block")

    same = "留短黑发的男性"
    cases = [("方位各不相同", ["left", "center", "right"]),
             ("方位全撞车", ["center", "center", "center"]),
             ("方位全缺失", ["", "", ""])]
    rows: list[tuple[str, bool, str]] = []
    for label, poss in cases:
        fr = [{"id": f"P{i + 1}", "present": True, "position": poss[i],
               "desc_zh": same, "appearances": [{"start": 0, "end": 5}]}
              for i in range(3)]
        try:
            p = _es.compile_prompt(
                "volc", _es.normalize({"person": True, "person_ids": ["P1", "P2"]}),
                model=SD_M, source_people=[fr[0], fr[1]], frame_people=fr,
                desc_by_id={x["id"]: {"zh": x["desc_zh"], "en": ""} for x in fr},
                slots=["person", "person2"])
        except Exception as e:  # noqa: BLE001
            rows.append((label, False, f"编译器崩了：{e}"))
            continue
        # 🩸 2026-10-30：`<主体N>` 定义句停用 ⇒ 判「分不分得开」要看**替换句宾语**
        #   （那就是编译器实际写出来的指认）。空集恒真的坑仍在：一条都没写出来时
        #   `len==len(set)` 会让两个 0 相等被当成「分得开」。
        objs = [x.strip() for x in re.findall(
            r"将其中的(.{1,40}?)(?:完整)?替换为@图片\d+中的人物", p)]
        separable = (len(objs) == 2 and len(set(objs)) == 2
                     and all(o != "人物" for o in objs))
        g = _gate(fr, ["P1", "P2"])
        rows.append((label, _ok(separable, g),
                     f"{'分得开' if separable else '分不开'} / 闸 {g}"
                     + ("" if _ok(separable, g) else " → 两边不是一把尺")))
    # 鉴别力自证：造一个「分不开却放行」的组合，一致性判据必须报红
    caught = not _ok(False, "pass")
    rows.append(("鉴别力自证（分不开却放行必须报红）", caught,
                 "抓到" if caught else "放过了 → 整组判据无鉴别力"))
    return rows


